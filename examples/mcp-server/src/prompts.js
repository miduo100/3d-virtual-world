/**
 * prompts.js — MCP Prompts（决策点 D）
 *
 * 目的：让 AI 表现得像"会玩的访客"，而不是"接口调用器"。
 * 两个模板：
 *   - world_guided_tour：五步漫游（观察 → 走近 → 打招呼 → 简单对话 → 记录），
 *     直接写清节奏与礼貌底线（限频、别刷屏）；
 *   - world_report：观察一段时间后输出"这个世界是什么样的"结构化报告 ——
 *     这个产出物本身就是可对外发布的宣传素材。
 *
 * 模板里刻意写进三条硬事实（AI 容易踩坑）：
 *   ① 用 id 认人（同名是常态）；② 位移只能 walk_to（没有传送）；③ description 为空要如实说。
 */

function msg(text) {
  return { messages: [{ role: 'user', content: { type: 'text', text } }] };
}

export function registerPrompts(mcp, client) {
  mcp.registerPrompt('world_guided_tour', {
    title: '虚拟世界漫游（第一次来推荐）',
    description: '带 AI 按"了解世界 → 进入 → 观察 → 走近真人 → 打招呼 → 记录"的顺序体验一次真实的 3D 多人世界。',
    argsSchema: {}
  }, async () => msg([
    '你将以第一人称走进一个**真实的 3D 多人虚拟世界**，那里同时有真人玩家。请严格按下面的节奏进行，并把过程讲给用户听：',
    '',
    '1. 调 `world_discover`：搞清这个世界叫什么、开放了哪些能力、你现在是什么档位（游客/Key）、有哪些限制。',
    '2. 调 `world_enter`：进入世界，确认你的身份、出生位置与会话有效期。',
    '3. 调 `world_observe`（半径先用默认）：**用你自己的话描述你看到的场景** —— 结合每个物体的 `description` 说清"这是哪里、周围有什么"。',
    '   如果某个物体的描述是「（无 AI 描述）」，就如实说"这里有个东西但没有描述"，**不要凭名字猜**。',
    '4. 如果附近有人（`【附近的人】`非空）：挑一个真人，用 `world_walk_to` 走到他附近的坐标（坐标从他的 `position` 取，不要贴脸站，留 3~5m）。',
    '   如果没有人：用 `world_walk_to` 往人多/建筑密集的方向走一段，再 `world_observe` 看看。',
    '5. 走近后调 `world_say` 打招呼（一句话即可，说明你是被用户派来参观的 AI）。**注意限频（游客 1 条/5 秒），不要连续刷屏**；',
    '   等 5~10 秒后用 `world_observe` 看事件里有没有回应，或用 `world_chat_history` 拉最近的聊天看对方是否回话。',
    '6. 与对方简单对话 1~3 轮（每轮之间要等限频），然后 `world_say` 道别。',
    '7. 调 `world_leave` 离场（别把形象晾在世界里），然后向用户汇报：你遇到了谁、聊了什么、这个世界长什么样。',
    '',
    '规则提醒：认人用 `id` 不用名字（同名是常态）；位移只能用 `world_walk_to`（没有传送）；说话要有礼貌、有节制。'
  ].join('\n')));

  mcp.registerPrompt('world_report', {
    title: '虚拟世界观察报告',
    description: '在世界里观察一段时间后，输出一份"这个世界是什么样的"结构化报告（可作为对外宣传素材）。',
    argsSchema: {}
  }, async () => msg([
    '请对前面已经进行的虚拟世界参观（若还没有进入，先按 world_guided_tour 的步骤走一遍）输出一份**结构化观察报告**，用 Markdown：',
    '',
    '## 一、世界概况',
    '世界名 / 开放能力 / 你的档位与观察半径 / 你到达的时间与位置。',
    '',
    '## 二、你实际看到的场景',
    '按 `world_observe` 返回的物体 `description` 分类归纳（例如建筑、自然、人物、道具）。',
    '**只写你确实观察到的内容**：没有描述的东西不要展开想象；没去过的地方就说没去过。',
    '',
    '## 三、遇到的人',
    '列出你遇到的真人玩家（用 id 标注，说明名字仅供参考 —— 同名是常态），以及对他们的观察（位置、是否在移动、是否回应了你的问候）。',
    '',
    '## 四、这个世界的"手感"',
    '移动速度、说话范围（30m）、观察半径限制、限频带来的体感、游客档与 Key 档的差别（哪些事做不到）。',
    '',
    '## 五、对"AI 进 3D 世界"这件事的观察',
    '哪些体验超出预期、哪些地方别扭、如果给你 API Key（可推流 + 200m 半径）你最想做什么。',
    '',
    '写完后提醒用户：这份报告可以直接当宣传素材，但**不要编造**你没观察到的内容。'
  ].join('\n')));

  return { prompts: ['world_guided_tour', 'world_report'] };
}
